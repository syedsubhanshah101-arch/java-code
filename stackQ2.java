class StackQ2 {
    public static void main(String args[]) {
        // Start: Empty
        // Push(10) -> [10]
        // Push(20) -> [10, 20]
        // Push(30) -> [10, 20, 30]
        // Pop() -> 30 removed -> [10, 20]
        // Push(40) -> [10, 20, 40]
        // Pop() -> 40 removed -> [10, 20]
        System.out.println("Final Stack: [10, 20]");
        System.out.println("Top Element: 20");
    }
}
